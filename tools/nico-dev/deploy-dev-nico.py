#!/usr/bin/env python3
"""
nico-dev — Deploy Nico helm stack on the dev kubeadm cluster.

Runs on the Mac (canonical) or the VM — helm/kubectl reach the cluster via the
site kubeconfig either way. The cluster pulls images from the Mac registry
(192.168.64.1:5000 as seen from the VM).

Helm values are generated by generate_dev_values.py into {site}/dev-values/
on every run (cert-manager.yaml, vault.yaml, eso.yaml, zalando-postgres-op.yaml,
nico-prereqs.yaml, nico.yaml — nico.yaml embeds the nico-api siteConfig TOML).

Usage:
  python3 deploy-dev-nico.py <site> --tag <tag>
  python3 deploy-dev-nico.py <site> --skip-to <release>   # resume from a release
  python3 deploy-dev-nico.py <site> --only <release>      # redeploy one release

Release order:
  local-path-provisioner → cert-manager → vault → external-secrets
  → postgres-operator → nico-prereqs → nico

Recovery:
  Stuck helm releases (pending-install/pending-upgrade/failed) are healed
  automatically before each install. Do NOT delete the nico-system namespace
  to recover — it holds the helm release state for nico-prereqs AND nico;
  deleting it destroys both and races against namespace termination. Use
  --only/--skip-to instead.
"""

import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

try:
    import yaml
except ImportError:
    print('Error: pyyaml not installed. Run: sudo apt install python3-yaml')
    sys.exit(1)


DEPLOY_ORDER = [
    'local-path-provisioner',
    'cert-manager',
    'vault',
    'external-secrets',
    'postgres-operator',
    'nico-prereqs',
    'nico',
    # NICo REST stack (nico-system.rest.enabled in the site yaml, default true):
    'rest-postgres',
    'keycloak',
    'temporal',
    'nico-rest',
    'nico-rest-site-agent',
]

# Steps installed as helm releases: DEPLOY_ORDER entry → (release, namespace).
# rest-postgres (kustomize) and keycloak (kubectl apply) are workload-checked.
HELM_RELEASE_OF = {
    'local-path-provisioner': ('local-path-provisioner', 'local-path-storage'),
    'cert-manager':           ('cert-manager',           'cert-manager'),
    'vault':                  ('vault',                  'vault'),
    'external-secrets':       ('external-secrets',       'external-secrets'),
    'postgres-operator':      ('postgres-operator',      'postgres'),
    'nico-prereqs':           ('nico-prereqs',           'nico-system'),
    'nico':                   ('nico',                   'nico-system'),
    'temporal':               ('temporal',               'temporal'),
    'nico-rest':              ('nico-rest',              'nico-rest'),
    'nico-rest-site-agent':   ('nico-rest-site-agent',   'nico-rest'),
}
_REST_STEPS = {'rest-postgres', 'keycloak', 'temporal', 'nico-rest',
               'nico-rest-site-agent'}


def resolve_site(arg):
    p = Path(arg).expanduser()
    if p.is_dir():
        yamls = [f for f in p.glob('*.yaml') if '.kubeconfig' not in f.name]
        if not yamls:
            print(f'Error: no site yaml in {p}', file=sys.stderr); sys.exit(1)
        if len(yamls) > 1:
            print(f'Error: multiple yamls in {p}', file=sys.stderr); sys.exit(1)
        return str(yamls[0]), str(p)
    return str(p), str(Path(p).parent)


def run(cmd, env=None, check=True, capture=False, stdin=None, timeout=600):
    e = {**os.environ, **(env or {})}
    r = subprocess.run(cmd, capture_output=capture, text=True,
                       env=e, input=stdin, timeout=timeout)
    if check and r.returncode != 0:
        print(f'  ! failed: {(r.stderr or r.stdout or "").strip()}', file=sys.stderr)
        sys.exit(1)
    return r


def helm(args, kubeconfig, timeout=600):
    return run(['helm'] + args, env={'KUBECONFIG': kubeconfig}, timeout=timeout)


def kubectl(args, kubeconfig, capture=True, check=True, stdin=None):
    return run(['kubectl'] + args, env={'KUBECONFIG': kubeconfig},
               capture=capture, check=check, stdin=stdin)


def heal_stuck_release(release, ns, kubeconfig):
    """Clear a helm release stuck in a pending/failed state.

    An interrupted helm run leaves the release secret in pending-install or
    pending-upgrade; the next 'helm upgrade --install' then fails with
    'another operation is in progress'. Deleting the pending secret rolls the
    release back to its last completed revision (or to absent, for a first
    install) so the retry proceeds — this is the documented recovery that
    users previously had to run by hand.
    """
    r = run(['helm', 'status', release, '-n', ns],
            env={'KUBECONFIG': kubeconfig}, check=False, capture=True)
    if r.returncode != 0:
        return   # release doesn't exist — nothing to heal
    for line in r.stdout.splitlines():
        if line.startswith('STATUS:'):
            status = line.split(':', 1)[1].strip()
            if status in ('pending-install', 'pending-upgrade', 'pending-rollback',
                          'failed', 'uninstalling'):
                print(f'  healing stuck release {release} (status: {status})')
                kubectl(['delete', 'secret', '-n', ns,
                         '-l', f'owner=helm,name={release},status={status}'],
                        kubeconfig, check=False)
            break


def ensure_nico_namespace(kubeconfig):
    """Create/adopt the nico-system namespace, safely.

    Handles the exists/absent flip-flop users hit during recovery:
    - If the namespace is Terminating (a previous recovery deleted it), WAIT
      for the deletion to finish — creating or installing into a Terminating
      namespace fails with confusing errors on both sides.
    - Create it if absent (idempotent), then apply helm ownership labels so
      the nico-prereqs chart can adopt it (helm refuses to adopt an unlabeled
      pre-existing namespace).
    """
    deadline = time.time() + 180
    warned = False
    while time.time() < deadline:
        r = kubectl(['get', 'namespace', 'nico-system',
                     '-o', 'jsonpath={.status.phase}'], kubeconfig, check=False)
        phase = r.stdout.strip()
        if phase != 'Terminating':
            break
        if not warned:
            print('  nico-system namespace is Terminating — waiting for deletion to finish...')
            warned = True
        time.sleep(5)
    else:
        print('Error: nico-system namespace stuck Terminating after 180s.', file=sys.stderr)
        print('  Inspect: kubectl get namespace nico-system -o yaml (look at finalizers)',
              file=sys.stderr)
        sys.exit(1)

    kubectl(['create', 'namespace', 'nico-system'], kubeconfig, check=False)
    kubectl(['label', 'namespace', 'nico-system',
             'app.kubernetes.io/managed-by=Helm', '--overwrite'], kubeconfig, check=False)
    kubectl(['annotate', 'namespace', 'nico-system',
             'meta.helm.sh/release-name=nico-prereqs',
             'meta.helm.sh/release-namespace=nico-system', '--overwrite'],
            kubeconfig, check=False)


def preflight_skipped_prereqs(target, vault_mode, rest_enabled, kubeconfig):
    """--skip-to/--only assume every earlier step is deployed AND healthy.

    Verify that instead of assuming it: a missing/failed helm release, an
    uninitialized vault, or a crashlooping pod in a skipped step makes the
    resumed deploy fail later in a far more confusing way. Hard-errors with
    cleanup guidance.
    """
    import json as _json

    prereqs = DEPLOY_ORDER[:DEPLOY_ORDER.index(target)]
    if not prereqs:
        return
    print(f'\nPreflight: verifying {len(prereqs)} skipped prerequisite steps...')

    r = run(['helm', 'list', '-A', '-o', 'json'],
            env={'KUBECONFIG': kubeconfig}, capture=True)
    try:
        status_of = {rel['name']: rel['status']
                     for rel in _json.loads(r.stdout or '[]')}
    except ValueError:
        status_of = {}

    problems   = []
    namespaces = set()
    for step in prereqs:
        if step in _REST_STEPS and not rest_enabled:
            continue
        if step in HELM_RELEASE_OF:
            rel, ns = HELM_RELEASE_OF[step]
            namespaces.add(ns)
            st = status_of.get(rel)
            if st is None:
                problems.append(f'{step}: helm release "{rel}" not found — '
                                f'skipped but never deployed')
            elif st != 'deployed':
                problems.append(f'{step}: helm release "{rel}" is "{st}" '
                                f'(expected "deployed")')
        elif step == 'rest-postgres':
            namespaces.add('postgres')
            if kubectl(['get', 'statefulset', 'postgres', '-n', 'postgres'],
                       kubeconfig, check=False).returncode != 0:
                problems.append('rest-postgres: statefulset postgres/postgres '
                                'not found — skipped but never deployed')
        elif step == 'keycloak':
            namespaces.add('nico-rest')
            if kubectl(['get', 'deployment', 'keycloak', '-n', 'nico-rest'],
                       kubeconfig, check=False).returncode != 0:
                problems.append('keycloak: deployment nico-rest/keycloak '
                                'not found — skipped but never deployed')

    if 'vault' in prereqs and vault_mode == 'file':
        if kubectl(['get', 'secret', 'vault-init-keys', '-n', 'vault'],
                   kubeconfig, check=False).returncode != 0:
            problems.append('vault: vault-init-keys secret missing — vault '
                            'was never initialized (file mode)')

    # Broken pods anywhere in the skipped steps' namespaces
    bad_states = ('CrashLoopBackOff', 'Error', 'ImagePullBackOff',
                  'ErrImagePull', 'CreateContainerConfigError', 'Failed')
    for ns in sorted(namespaces):
        r = kubectl(['get', 'pods', '-n', ns, '--no-headers'],
                    kubeconfig, check=False)
        for line in (r.stdout or '').splitlines():
            # Pods of the TARGET step share namespaces with skipped steps
            # (e.g. nico-rest-site-agent-0 in nico-rest); their brokenness is
            # what the resume is about to fix — don't block on it.
            if line.split()[0].startswith(target):
                continue
            if any(s in line for s in bad_states):
                problems.append(f'broken pod in skipped step namespace '
                                f'"{ns}": {" ".join(line.split()[:3])}')

    if problems:
        print('\nError: --skip-to/--only requires every skipped step to be '
              'healthy, but:', file=sys.stderr)
        for p in problems:
            print(f'  ✗ {p}', file=sys.stderr)
        print('\nClean up first:', file=sys.stderr)
        print('  - missing/pending/failed releases: re-run WITHOUT '
              '--skip-to/--only — already-deployed\n    releases are fast '
              'no-ops and pending-* states heal automatically', file=sys.stderr)
        print('  - broken pods: kubectl describe/logs them before '
              'redeploying', file=sys.stderr)
        print('  - never delete the nico-system namespace (helm release '
              'state lives there)', file=sys.stderr)
        sys.exit(1)
    print('  skipped prerequisites healthy ✓')


def ensure_vault_initialized(kubeconfig):
    """Initialize Vault (file mode) on first deploy; return root token.

    Idempotent: if already initialized, reads the token from the vault-init-keys
    k8s secret.  On first run: runs vault operator init, stores the single unseal
    key + root token in vault-init-keys, and immediately unseals.  After that the
    vault-unsealer sidecar container handles unsealing on every pod restart.
    """
    import base64
    import json as _json

    vault_ns  = 'vault'
    vault_pod = 'vault-0'

    # Wait for the Vault pod to reach Running state
    print('  Waiting for Vault pod...')
    deadline = time.time() + 120
    while time.time() < deadline:
        r = kubectl(['get', 'pod', vault_pod, '-n', vault_ns,
                     '-o', 'jsonpath={.status.phase}'], kubeconfig, check=False)
        if r.stdout.strip() == 'Running':
            break
        time.sleep(5)
    else:
        print('  Warning: Vault pod not Running after 2 min — proceeding anyway')

    # Check initialization state
    r = kubectl(['exec', '-n', vault_ns, vault_pod, '-c', 'vault', '--',
                 'vault', 'status', '-format=json'], kubeconfig, check=False)
    try:
        status = _json.loads(r.stdout)
        initialized = status.get('initialized', False)
    except Exception:
        initialized = False

    if initialized:
        # Already initialized — read token from persisted secret
        r = kubectl(['get', 'secret', 'vault-init-keys', '-n', vault_ns,
                     '-o', 'jsonpath={.data.root_token}'], kubeconfig, check=False)
        if r.returncode == 0 and r.stdout.strip():
            token = base64.b64decode(r.stdout.strip()).decode()
            print('  Vault already initialized ✓')
            return token
        print('  Warning: vault-init-keys secret not found — falling back to "root"')
        return 'root'

    # First initialization
    print('  Initializing Vault (first time)...')
    r = kubectl(['exec', '-n', vault_ns, vault_pod, '-c', 'vault', '--',
                 'vault', 'operator', 'init',
                 '-key-shares=1', '-key-threshold=1', '-format=json'], kubeconfig)
    init_data  = _json.loads(r.stdout)
    unseal_key = init_data['unseal_keys_b64'][0]
    root_token = init_data['root_token']

    # Persist keys — the vault-unsealer sidecar reads unseal_key on every restart
    kubectl(['create', 'secret', 'generic', 'vault-init-keys', '-n', vault_ns,
             f'--from-literal=unseal_key={unseal_key}',
             f'--from-literal=root_token={root_token}'], kubeconfig)
    print('  Vault initialized, keys stored in vault-init-keys secret ✓')

    # Unseal immediately (sidecar takes up to 60s to pick up the new secret volume)
    kubectl(['exec', '-n', vault_ns, vault_pod, '-c', 'vault', '--',
             'vault', 'operator', 'unseal', unseal_key], kubeconfig)
    print('  Vault unsealed ✓')

    return root_token


def wait_vault_ready(kubeconfig, timeout=120):
    """Hard gate: Vault must be initialized AND unsealed before anything
    consumes it (nico-prereqs' vault-pki-config job is the first consumer).

    Covers the OnDelete pod roll: a restarted vault-0 comes up sealed and
    the unsealer sidecar can take up to ~70s to catch it (secret volume
    propagation + 10s poll loop).
    """
    import json as _json
    print('  Waiting for Vault to be initialized + unsealed...')
    deadline = time.time() + timeout
    last = ''
    while time.time() < deadline:
        r = kubectl(['exec', '-n', 'vault', 'vault-0', '-c', 'vault', '--',
                     'vault', 'status', '-format=json'], kubeconfig, check=False)
        try:
            st = _json.loads(r.stdout)
            last = f'initialized={st.get("initialized")} sealed={st.get("sealed")}'
            if st.get('initialized') and not st.get('sealed'):
                print(f'  Vault ready ✓ ({last})')
                return
        except ValueError:
            last = (r.stderr or r.stdout or 'no response').strip()[:120]
        time.sleep(5)
    print(f'  Error: Vault not ready after {timeout}s ({last})', file=sys.stderr)
    print('  Diagnose: kubectl get pods -n vault; '
          'kubectl logs vault-0 -n vault -c vault', file=sys.stderr)
    sys.exit(1)


def ensure_ssh_host_key(ns, kubeconfig):
    """Pre-create ssh-host-key secret in OpenSSH format before nico-prereqs install.

    helm genPrivateKey produces PKCS#8 ("BEGIN PRIVATE KEY") but ssh-console-rs
    requires OpenSSH format ("BEGIN OPENSSH PRIVATE KEY").  ssh-keygen -t ed25519
    always writes OpenSSH format.  Idempotent: skips if the secret already exists.
    """
    r = kubectl(['get', 'secret', 'ssh-host-key', '-n', ns], kubeconfig, check=False)
    if r.returncode == 0:
        print('  ssh-host-key already exists — skipping')
        return

    import tempfile
    with tempfile.TemporaryDirectory() as tmpdir:
        keyfile = f'{tmpdir}/ssh_host_ed25519_key'
        run(['ssh-keygen', '-t', 'ed25519', '-N', '', '-f', keyfile, '-C', '', '-q'])
        kubectl(['create', 'secret', 'generic', 'ssh-host-key',
                 '-n', ns,
                 f'--from-file=ssh_host_ed25519_key={keyfile}',
                 f'--from-file=ssh_host_ed25519_key_pub={keyfile}.pub'],
                kubeconfig)
        kubectl(['label', 'secret', 'ssh-host-key', '-n', ns,
                 'app.kubernetes.io/managed-by=Helm', '--overwrite'], kubeconfig)
        kubectl(['annotate', 'secret', 'ssh-host-key', '-n', ns,
                 'meta.helm.sh/release-name=nico-prereqs',
                 'meta.helm.sh/release-namespace=nico-system', '--overwrite'], kubeconfig)
    print('  ssh-host-key created (OpenSSH format) ✓')


def patch_allow_insecure_discovery(ns, kubeconfig):
    """Prepend allow_insecure_discovery=true before the first [section] in nico-api config."""
    cm  = 'nico-api-config-files'
    add = 'allow_insecure_discovery = true\n'

    r = subprocess.run(
        ['kubectl', '--kubeconfig', kubeconfig, 'get', 'configmap', cm,
         '-n', ns, '-o', 'json'],
        capture_output=True, text=True
    )
    if r.returncode != 0:
        return

    import json as _json
    data = _json.loads(r.stdout).get('data', {})
    patched = False
    for key in ['nico-api-config.toml', 'carbide-api-config.toml']:
        if key not in data or 'allow_insecure_discovery' in data[key]:
            continue
        lines = data[key].splitlines(keepends=True)
        pos = next((i for i, l in enumerate(lines) if l.strip().startswith('[')), len(lines))
        lines.insert(pos, add)
        data[key] = ''.join(lines)
        patched = True

    if not patched:
        return

    patch = _json.dumps({'data': {k: data[k] for k in data
                                   if k in ['nico-api-config.toml', 'carbide-api-config.toml']}})
    subprocess.run(
        ['kubectl', '--kubeconfig', kubeconfig, 'patch', 'configmap', cm,
         '-n', ns, '--type=merge', '-p', patch],
        capture_output=True
    )
    subprocess.run(
        ['kubectl', '--kubeconfig', kubeconfig, 'rollout', 'restart',
         'deployment/nico-api', '-n', ns],
        capture_output=True
    )
    print('  allow_insecure_discovery patched ✓')


