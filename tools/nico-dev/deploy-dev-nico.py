def resolve_repo(cfg):
    """Resolve the nico repo path: nico_repo_folder joined onto whichever share
    root is accessible from here (Mac first, then VM)."""
    repo_folder = cfg.get('nico_repo_folder', 'infra-controller-core')
    nico_mac = cfg.get('nico_mac_folder', '')
    nico_vm  = cfg.get('nico_vm_folder', '')
    if nico_mac and Path(nico_mac).expanduser().exists():
        return str(Path(nico_mac).expanduser() / repo_folder)
    if nico_vm and Path(nico_vm).expanduser().exists():
        return str(Path(nico_vm).expanduser() / repo_folder)
    # backward compat
    return cfg.get('infra_controller_repo', '')


def main():
    p = argparse.ArgumentParser()
    p.add_argument('site')
    p.add_argument('--tag', default=None,
                   help='Image tag to deploy (overrides registry.nico_tag in site yaml)')
    p.add_argument('--skip-to', default=None,
                   help=f'Resume: skip releases BEFORE this one, deploy it and all after '
                        f'({", ".join(DEPLOY_ORDER)})')
    p.add_argument('--only', default=None,
                   help='Redeploy exactly ONE release, skip everything else')
    args = p.parse_args()

    if args.skip_to and args.only:
        print('Error: --skip-to and --only are mutually exclusive', file=sys.stderr)
        sys.exit(1)

    site_yaml, site_folder = resolve_site(args.site)
    cfg = yaml.safe_load(open(site_yaml))
    dc  = cfg['fabric']['dc_name']

    # Override tag if provided
    if args.tag:
        cfg.setdefault('registry', {})['nico_tag'] = args.tag

    sitename      = cfg.get('nico-system', {}).get('helm-values', {}).get('sitename', 'dev')
    kube_filename = cfg.get('kubeconfig', f'{dc}-{sitename}.kubeconfig.yaml')
    kubeconfig    = str(Path(site_folder) / kube_filename)
    repo          = resolve_repo(cfg)
    helm_dir      = str(Path(repo) / 'helm')
    prereqs_dir   = str(Path(repo) / 'helm-prereqs')

    chart_versions = cfg.get('chart-versions', {})

    if not Path(kubeconfig).exists():
        print(f'Error: kubeconfig not found: {kubeconfig}', file=sys.stderr)
        print('  Run deploy-dev-cp.py first.', file=sys.stderr)
        sys.exit(1)

    # ── Preflight: registry reachable and image exists ────────────────────────
    reg_host = cfg.get('registry', {}).get('host', '192.168.64.1')
    reg_port = cfg.get('registry', {}).get('port', 5000)
    registry = f'{reg_host}:{reg_port}'
    nico_tag = cfg.get('registry', {}).get('nico_tag', 'latest')
    print(f'\nPreflight: checking registry {registry} has nico:{nico_tag}...')
    # Accept EVERY manifest flavour: Docker with the containerd image store
    # (Linux hosts) pushes OCI manifests, and registry:2 answers a request
    # whose Accept lacks the OCI type with 404 "manifest unknown" — which
    # looked like "image not found" on the first Linux bring-up (20260902-#6).
    accept = ', '.join([
        'application/vnd.oci.image.manifest.v1+json',
        'application/vnd.oci.image.index.v1+json',
        'application/vnd.docker.distribution.manifest.v2+json',
        'application/vnd.docker.distribution.manifest.list.v2+json'])
    reach = subprocess.run(['curl', '-sf', '-m', '10', f'http://{registry}/v2/'],
                           capture_output=True, text=True)
    if reach.returncode != 0:
        print(f'  Error: cannot reach registry {registry} from here (curl exit '
              f'{reach.returncode})', file=sys.stderr)
        print('  ensure-registry.py starts it; from a Linux host a timeout means '
              'the firewall drops host↔registry traffic.', file=sys.stderr)
        sys.exit(1)
    r = subprocess.run(
        ['curl', '-sf', '-m', '10', '-o', '/dev/null',
         f'http://{registry}/v2/nico/manifests/{nico_tag}', '-H', f'Accept: {accept}'],
        capture_output=True, text=True
    )
    if r.returncode != 0:
        tags = subprocess.run(['curl', '-s', '-m', '10',
                               f'http://{registry}/v2/nico/tags/list'],
                              capture_output=True, text=True).stdout.strip()
        print(f'  Error: image nico:{nico_tag} not in registry {registry}', file=sys.stderr)
        print(f'  tags present: {tags or "(none)"}', file=sys.stderr)
        print(f'  Run build-dev-nico.py (source) or deploy-nico-from-ngc.py '
              f'(NGC) to push it first.', file=sys.stderr)
        sys.exit(1)
    print(f'  registry {registry}/nico:{nico_tag} ✓')

    for flag, val in [('--skip-to', args.skip_to), ('--only', args.only)]:
        if val and val not in DEPLOY_ORDER:
            print(f'Error: unknown release "{val}" for {flag}', file=sys.stderr)
            print(f'  Valid: {", ".join(DEPLOY_ORDER)}', file=sys.stderr)
            sys.exit(1)

    if args.only:
        skip_set = set(DEPLOY_ORDER) - {args.only}
    elif args.skip_to:
        skip_set = set(DEPLOY_ORDER[:DEPLOY_ORDER.index(args.skip_to)])
    else:
        skip_set = set()

    def skip(release):
        if release in skip_set:
            print(f'  skipping {release}')
            return True
        return False

    if args.skip_to or args.only:
        preflight_skipped_prereqs(
            args.skip_to or args.only,
            cfg.get('nico-system', {}).get('vault', {}).get('mode', 'file'),
            cfg.get('nico-system', {}).get('rest', {}).get('enabled', True),
            kubeconfig)

    # Generate all values files via generate-dev-values.py
    vals_dir = Path(site_folder) / 'dev-values'
    vals_dir.mkdir(exist_ok=True)
    sys.path.insert(0, str(Path(__file__).parent))
    from generate_dev_values import generate as gen_values
    gen_values(cfg, vals_dir)
    print(f'Values generated → {vals_dir}')

    print('nico-dev — Deploy Nico')
    print(f'  site      : {site_yaml}')
    print(f'  kubeconfig: {kubeconfig}')
    print(f'  repo      : {repo}')

    # ── local-path-provisioner ────────────────────────────────────────────────
    if not skip('local-path-provisioner'):
        print('\nInstalling local-path-provisioner...')
        helm(['repo', 'add', 'containeroo', 'https://charts.containeroo.ch'], kubeconfig)
        helm(['repo', 'update', 'containeroo'], kubeconfig)
        helm(['upgrade', '--install', 'local-path-provisioner',
              'containeroo/local-path-provisioner',
              '-n', 'local-path-storage', '--create-namespace',
              '--wait'], kubeconfig)
        # Mark it the DEFAULT StorageClass: upstream manifests written for
        # kind (e.g. the rest-postgres kustomize base) omit storageClassName
        # and rely on a cluster default — without one their PVCs sit Pending
        # forever. Sole storage class on a single-node dev cluster → default.
        kubectl(['annotate', 'storageclass', 'local-path',
                 'storageclass.kubernetes.io/is-default-class=true',
                 '--overwrite'], kubeconfig)
        print('  local-path-provisioner ✓ (default StorageClass)')

    # ── cert-manager ──────────────────────────────────────────────────────────
    if not skip('cert-manager'):
        print('\nInstalling cert-manager...')
        ver = chart_versions.get('cert-manager', 'v1.17.1')
        helm(['repo', 'add', 'jetstack', 'https://charts.jetstack.io'], kubeconfig)
        helm(['upgrade', '--install', 'cert-manager', 'jetstack/cert-manager',
              '--version', ver,
              '-n', 'cert-manager', '--create-namespace',
              '--set', 'crds.enabled=true',
              '--wait'], kubeconfig)
        print('  cert-manager ✓')

    # ── vault ─────────────────────────────────────────────────────────────────
    vault_mode = cfg.get('nico-system', {}).get('vault', {}).get('mode', 'file')
    if not skip('vault'):
        print(f'\nInstalling Vault ({vault_mode} mode)...')
        helm(['repo', 'add', 'hashicorp', 'https://helm.releases.hashicorp.com'], kubeconfig)
        helm(['upgrade', '--install', 'vault', 'hashicorp/vault',
              '--version', chart_versions.get('vault', '0.25.0'),
              '-n', 'vault', '--create-namespace',
              '-f', str(vals_dir / 'vault.yaml'),
              '--wait'], kubeconfig)
        # The vault chart's statefulset uses updateStrategy OnDelete: a helm
        # upgrade rewrites the pod template but the RUNNING pod keeps the old
        # spec until deleted. Roll it if it is not on the latest revision.
        want = kubectl(['get', 'statefulset', 'vault', '-n', 'vault', '-o',
                        'jsonpath={.status.updateRevision}'],
                       kubeconfig, check=False).stdout.strip()
        have = kubectl(['get', 'pod', 'vault-0', '-n', 'vault', '-o',
                        'jsonpath={.metadata.labels.controller-revision-hash}'],
                       kubeconfig, check=False).stdout.strip()
        if want and have and want != have:
            print('  vault-0 runs an outdated spec (OnDelete strategy) — restarting it...')
            kubectl(['delete', 'pod', 'vault-0', '-n', 'vault'],
                    kubeconfig, check=False)
        print('  vault ✓')

    # Resolve vault root token (needed for nico-prereqs regardless of skip_set)
    if vault_mode == 'file':
        vault_token = ensure_vault_initialized(kubeconfig)
    else:
        vault_token = cfg.get('nico-system', {}).get('vault', {}).get('dev_root_token', 'root')
    wait_vault_ready(kubeconfig)

    # ── external-secrets ──────────────────────────────────────────────────────
    if not skip('external-secrets'):
        print('\nInstalling external-secrets...')
        helm(['repo', 'add', 'external-secrets',
              'https://charts.external-secrets.io'], kubeconfig)
        helm(['upgrade', '--install', 'external-secrets',
              'external-secrets/external-secrets',
              '--version', chart_versions.get('external-secrets', '0.14.3'),
              '-n', 'external-secrets', '--create-namespace',
              '-f', str(vals_dir / 'eso.yaml'),
              '--wait'], kubeconfig)
        print('  external-secrets ✓')

    # ── postgres-operator ─────────────────────────────────────────────────────
    if not skip('postgres-operator'):
        print('\nInstalling postgres-operator...')
        helm(['repo', 'add', 'postgres-op',
              'https://opensource.zalando.com/postgres-operator/charts/postgres-operator'],
             kubeconfig)
        helm(['upgrade', '--install', 'postgres-operator',
              'postgres-op/postgres-operator',
              '--version', chart_versions.get('postgres-operator', '1.15.1'),
              '-n', 'postgres', '--create-namespace',
              '-f', str(vals_dir / 'zalando-postgres-op.yaml'),
              '--wait'], kubeconfig)
        print('  postgres-operator ✓')

    # ── nico-prereqs ──────────────────────────────────────────────────────────
    if not skip('nico-prereqs'):
        print('\nInstalling nico-prereqs...')
        ensure_nico_namespace(kubeconfig)
        heal_stuck_release('nico-prereqs', 'nico-system', kubeconfig)
        ensure_ssh_host_key('nico-system', kubeconfig)
        helm(['upgrade', '--install', 'nico-prereqs', prereqs_dir,
              '-n', 'nico-system',
              '-f', str(vals_dir / 'nico-prereqs.yaml'),
              '--set', f'vault.token={vault_token}',
              '--wait', '--timeout', '10m'], kubeconfig)

        # Wait for vault-pki-config job to complete before proceeding
        print('  Waiting for vault-pki-config job...')
        deadline = time.time() + 300
        while time.time() < deadline:
            r = kubectl(['get', 'job', 'vault-pki-config',
                         '-n', 'nico-system',
                         '-o', 'jsonpath={.status.succeeded}'],
                        kubeconfig, check=False)
            if r.stdout.strip() == '1':
                break
            time.sleep(5)
        else:
            print('  Error: vault-pki-config job did not complete in 5m — '
                  'nico needs its PKI in place.', file=sys.stderr)
            print('  Diagnose: kubectl logs job/vault-pki-config -n nico-system',
                  file=sys.stderr)
            sys.exit(1)

        # Wait for postgres cluster to be fully ready (2/2 containers running)
        print('  Waiting for nico-pg-cluster-0 to be Ready...')
        deadline = time.time() + 300
        while time.time() < deadline:
            r = kubectl(['get', 'pod', 'nico-pg-cluster-0',
                         '-n', 'postgres',
                         '-o', 'jsonpath={.status.conditions[?(@.type=="Ready")].status}'],
                        kubeconfig, check=False)
            if r.stdout.strip() == 'True':
                break
            time.sleep(5)
        else:
            print('  Error: nico-pg-cluster-0 not Ready in 5m — deploying nico '
                  'against an unready database fails in confusing ways.',
                  file=sys.stderr)
            print('  Diagnose: kubectl describe pod nico-pg-cluster-0 -n postgres; '
                  'kubectl logs postgres-operator -n postgres', file=sys.stderr)
            sys.exit(1)

        print('  nico-prereqs ✓')

    # ── nico ──────────────────────────────────────────────────────────────────
    if not skip('nico'):
        print('\nInstalling nico...')
        ensure_nico_namespace(kubeconfig)
        heal_stuck_release('nico', 'nico-system', kubeconfig)
        helm(['upgrade', '--install', 'nico', helm_dir,
              '-n', 'nico-system',
              '-f', str(vals_dir / 'nico.yaml'),
              '--wait', '--timeout', '15m'], kubeconfig)
        patch_allow_insecure_discovery('nico-system', kubeconfig)
        print('  nico ✓')

    # ── NICo REST stack (temporal + keycloak + umbrella + site-agent) ─────────
    # Base feature: all four developer surfaces (nico-admin-cli, nico-cli,
    # gRPC API, REST API) must work. Toggle: nico-system.rest.enabled.
    rest_enabled = cfg.get('nico-system', {}).get('rest', {}).get('enabled', True)
    if not rest_enabled:
        print('\nNICo REST stack: disabled in site yaml (nico-system.rest.enabled) — skipping')
    else:
        import rest_deploy
        rest_dir    = str(Path(repo) / 'rest-api')
        prereqs_ref = str(Path(repo) / 'helm-prereqs')
        if not Path(rest_dir).is_dir():
            print(f'Error: rest-api/ not found in the nico repo ({rest_dir}) — '
                  f'REST is enabled but the checkout has no REST tree.', file=sys.stderr)
            sys.exit(1)

        if not skip('rest-postgres'):
            print('\nInstalling rest-postgres (ns + CA + issuer + temporal/keycloak DB)...')
            rest_deploy.deploy_rest_postgres(rest_dir, kubeconfig)

        if not skip('keycloak'):
            print('\nInstalling keycloak (dev IdP)...')
            rest_deploy.deploy_keycloak(prereqs_ref, kubeconfig)

        if not skip('temporal'):
            print('\nInstalling temporal...')
            heal_stuck_release('temporal', 'temporal', kubeconfig)
            rest_deploy.deploy_temporal(rest_dir, kubeconfig)

        if not skip('nico-rest'):
            print('\nInstalling nico-rest umbrella...')
            heal_stuck_release('nico-rest', 'nico-rest', kubeconfig)
            rest_deploy.deploy_nico_rest(repo, rest_dir, kubeconfig,
                                         registry, nico_tag,
                                         vals_dir / 'nico-rest-dev.yaml')

        if not skip('nico-rest-site-agent'):
            print('\nInstalling nico-rest-site-agent...')
            heal_stuck_release('nico-rest-site-agent', 'nico-rest', kubeconfig)
            s_uuid = rest_deploy.site_uuid(site_folder)
            rest_deploy.deploy_site_agent(repo, kubeconfig, registry,
                                          nico_tag, s_uuid)

    here = Path(__file__).resolve().parent
    print(f'\n{"="*55}')
    print('  Nico deployed ✓')
    # images.tag in the site yaml = what the cluster runs now
    if args.tag:
        import importlib.util
        _spec = importlib.util.spec_from_file_location(
            'site_images', Path(__file__).resolve().parent / 'site_images.py')
        _si = importlib.util.module_from_spec(_spec)
        _spec.loader.exec_module(_si)
        _si.record(site_yaml, deployed_tag=args.tag)
        print(f'  site yaml images.tag = {args.tag} ✓')
    print(f'\n  Verify:')
    print(f'    kubectl --kubeconfig {kubeconfig} get pods -n nico-system')
    if rest_enabled:
        print(f'    kubectl --kubeconfig {kubeconfig} get pods -n nico-rest')
        print(f'    kubectl --kubeconfig {kubeconfig} get pods -n temporal')
        print(f'\n  REST API (NodePort, production parity): http://<vm-ip>:30388')
    print(f'\n  Next — build and configure the CLIs (on Mac):')
    print(f'    python3 {here}/build-nico-clis.py {args.site} --install-to ~/.local/bin')
    print(f'    python3 {here}/configure-clis.py {args.site}')
    print(f'{"="*55}')


if __name__ == '__main__':
    main()
